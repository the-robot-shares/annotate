defmodule AnnotateWeb.Plugs.SEO do
  @moduledoc """
  Serves the crawler-facing files and applies indexing headers.

  * `GET /robots.txt`, `/sitemap.xml`, `/llms.txt`, `/llms-full.txt` are
    generated by `AnnotateWeb.SEO` (nothing hand-maintained in `priv/static`).
    The API host (annotate-srv) answers `robots.txt` with `Disallow: /` and
    serves none of the others.
  * Every response from the API host carries `X-Robots-Tag: noindex, nofollow`;
    so do app/auth/dashboard paths on any host (belt and braces next to the
    `<meta name="robots">` the layouts render).
  * `/` on the marketing host gets JSON-LD injected into `<head>` at send time,
    straight from the rendered HTML. It is deliberately NOT page state: state is
    serialised into Hologram's hydration payload, where a stray `</script`
    would break out of the inline script.

  Runs before `Plug.Static`.
  """

  import Plug.Conn

  alias AnnotateWeb.SEO

  @txt "text/plain; charset=utf-8"
  @xml "application/xml; charset=utf-8"

  def init(opts), do: opts

  def call(conn, _opts) do
    api? = SEO.api_host?(conn.host)

    conn
    |> noindex_header(api?)
    |> serve(api?)
  end

  defp noindex_header(conn, api?) do
    if api? or SEO.noindex_path?(conn.path_info) do
      put_resp_header(conn, "x-robots-tag", "noindex, nofollow")
    else
      conn
    end
  end

  defp serve(%Plug.Conn{method: m, path_info: ["robots.txt"]} = conn, api?)
       when m in ~w(GET HEAD) do
    send_file_like(conn, @txt, SEO.robots_txt(if api?, do: :api, else: :marketing))
  end

  defp serve(%Plug.Conn{method: m, path_info: [file]} = conn, false)
       when m in ~w(GET HEAD) and file in ~w(sitemap.xml llms.txt llm.txt llms-full.txt) do
    case file do
      "sitemap.xml" -> send_file_like(conn, @xml, SEO.sitemap_xml())
      # llm.txt: legacy alias some fleet tooling checks (byte-identical to llms.txt).
      f when f in ~w(llms.txt llm.txt) -> send_file_like(conn, @txt, SEO.llms_txt())
      "llms-full.txt" -> send_file_like(conn, @txt, SEO.llms_full_txt())
    end
  end

  defp serve(%Plug.Conn{method: "GET", path_info: []} = conn, false) do
    register_before_send(conn, &inject_json_ld/1)
  end

  defp serve(conn, _api?), do: conn

  defp send_file_like(conn, content_type, body) do
    conn
    |> put_resp_content_type(content_type, nil)
    |> put_resp_header("cache-control", "public, max-age=3600")
    |> send_resp(200, body)
    |> halt()
  end

  defp inject_json_ld(%Plug.Conn{status: 200} = conn) do
    with [ct | _] <- get_resp_header(conn, "content-type"),
         true <- String.starts_with?(ct, "text/html"),
         body when is_binary(body) <- body_to_binary(conn.resp_body),
         [head, rest] <- String.split(body, "</head>", parts: 2) do
      tag = body |> SEO.faq_from_html() |> SEO.landing_json_ld() |> SEO.json_ld_script()
      %{conn | resp_body: [head, tag, "</head>", rest]}
    else
      _ -> conn
    end
  end

  defp inject_json_ld(conn), do: conn

  defp body_to_binary(nil), do: nil
  defp body_to_binary(body), do: IO.iodata_to_binary(body)
end
